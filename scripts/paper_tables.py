#!/usr/bin/env python3
"""Create compact paper-facing tables from the three lossless benchmark tables."""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as stream:
        return list(csv.DictReader(stream))


def number(row: dict[str, str], key: str, default: float = 0.0) -> float:
    value = row.get(key, "")
    return default if value in (None, "", "NA") else float(value)


def integer(value: float) -> str:
    return str(int(round(value)))


def fixed(value: float, digits: int = 3) -> str:
    return f"{value:.{digits}f}"


def mean_std(mean: float, std: float, digits: int = 2) -> str:
    return f"{mean:.{digits}f} ± {std:.{digits}f}"


def percent(value: float) -> str:
    return f"{100.0 * value:.1f}"


def percent_already_scaled(value: float, std: float) -> str:
    return mean_std(value, std, 1)


def _write_table(title: str, rows: list[dict[str, str]], base: Path,
                 print_table: bool = True) -> None:
    fields = list(rows[0]) if rows else []
    with base.with_suffix(".csv").open("w", newline="", encoding="utf-8") as stream:
        writer = csv.DictWriter(stream, fieldnames=fields)
        writer.writeheader()
        writer.writerows(rows)
    lines = [f"# {title}", "", "| " + " | ".join(fields) + " |",
             "|" + "|".join("---" if i < 2 else "---:"
                                for i in range(len(fields))) + "|"]
    lines.extend("| " + " | ".join(row[field] for field in fields) + " |"
                 for row in rows)
    markdown = "\n".join(lines) + "\n"
    base.with_suffix(".md").write_text(markdown, encoding="utf-8")
    latex_fields = {
        "$n$": "$n$", "Success (\\%)": "Success (\\%)",
        "Objects completed (\\%)": "Objects completed (\\%)",
        "Planner success (\\%)": "Planner success (\\%)",
    }

    def latex(value: str) -> str:
        if value in latex_fields:
            return latex_fields[value]
        escaped = (value.replace("\\", "\\textbackslash{}")
                   .replace("&", "\\&").replace("%", "\\%")
                   .replace("_", "\\_").replace("#", "\\#"))
        if " ± " in escaped:
            left, right = escaped.split(" ± ", 1)
            return f"${left} \\pm {right}$"
        return escaped

    alignment = "ll" + "r" * max(0, len(fields) - 2)
    tex_lines = [
        "% Requires booktabs; generated by scripts/paper_tables.py.",
        "\\begin{table*}[t]", "\\centering", "\\scriptsize",
        "\\setlength{\\tabcolsep}{3pt}",
        f"\\caption{{{latex(title)}}}",
        f"\\label{{tab:{base.name.replace('_', '-')}}}",
        f"\\begin{{tabular}}{{{alignment}}}", "\\toprule",
        " & ".join(latex(field) for field in fields) + " \\\\",
        "\\midrule",
    ]
    tex_lines.extend(" & ".join(latex(row[field]) for field in fields) + " \\\\"
                     for row in rows)
    tex_lines.extend(["\\bottomrule", "\\end{tabular}", "\\end{table*}", ""])
    base.with_suffix(".tex").write_text("\n".join(tex_lines), encoding="utf-8")
    if print_table:
        print("\n" + markdown, flush=True)


def proposed_paper_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    result = []
    for row in rows:
        plan_time = number(row, "planner_preprocess_sec") + number(row, "planner_ILP_sec")
        result.append({
            "Case": row["case"],
            "Family": row.get("family", ""),
            "$n$": integer(number(row, "planner_n")),
            "Yaw model": row.get("isaac_yaw_type", ""),
            "Plan time (s)": fixed(plan_time, 4),
            "Actions": integer(number(row, "planner_physical_actions")),
            "Picks": integer(number(row, "planner_n")),
            "Knocks": integer(number(row, "planner_ILP_opt")),
            "Knock attempts": mean_std(number(row, "isaac_clearance_attempts_mean"),
                                         number(row, "isaac_clearance_attempts_std")),
            "Execution time (s)": mean_std(number(row, "isaac_execution_time_sec_mean"),
                                             number(row, "isaac_execution_time_sec_std")),
            "Success (\%)": percent(number(row, "isaac_success_rate")),
            "Objects completed (\%)": percent_already_scaled(
                number(row, "isaac_object_completion_percentage_mean"),
                number(row, "isaac_object_completion_percentage_std")),
        })
    return result


def random_knock_paper_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    result = []
    for row in rows:
        case = row["case"]
        family = row.get("family", "")
        n = number(row, "ours_n")
        ours_knocks = number(row, "ours_ILP_opt")
        ours_time = number(row, "ours_preprocess_sec") + number(row, "ours_ILP_sec")
        common = {"Case": case, "Family": family, "$n$": integer(n)}
        result.append({
            **common,
            "Method": "Optimal Knock--Pick",
            "Plan time (s)": mean_std(ours_time, 0.0, 4),
            "Actions": mean_std(n + ours_knocks, 0.0),
            "Picks": integer(n),
            "Knocks": integer(ours_knocks),
            "Random knocks": "--",
            "Excess knocks": "0.00",
            "Planner success (\%)": "100.0",
        })
        random_knocks = number(row, "random_clearance_knocks_mean")
        random_knocks_std = number(row, "random_clearance_knocks_std")
        result.append({
            **common,
            "Method": "Random feasible Knock",
            "Plan time (s)": mean_std(
                number(row, "ours_preprocess_sec") +
                number(row, "random_clearance_runtime_sec_mean"),
                number(row, "random_clearance_runtime_sec_std"), 4),
            "Actions": mean_std(number(row, "random_clearance_physical_actions_mean",
                                        n + random_knocks), random_knocks_std),
            "Picks": integer(n),
            "Knocks": "--",
            "Random knocks": mean_std(random_knocks, random_knocks_std),
            "Excess knocks": fixed(number(row, "random_clearance_regret_mean"), 2),
            "Planner success (\%)": percent(number(row, "random_clearance_success_rate")),
        })
    return result


def random_push_paper_rows(rows: list[dict[str, str]]) -> list[dict[str, str]]:
    result = []
    for row in rows:
        case = row["case"]
        family = row.get("family", "")
        n = number(row, "ours_planner_n")
        knocks = number(row, "ours_planner_ILP_opt")
        common = {"Case": case, "Family": family, "$n$": integer(n)}
        result.append({
            **common,
            "Method": "Optimal Knock--Pick",
            "Plan/replan time (s)": mean_std(
                number(row, "ours_planner_preprocess_sec") +
                number(row, "ours_planner_ILP_sec"), 0.0, 4),
            "Action attempts": mean_std(
                number(row, "ours_isaac_actions_planned_mean", n + knocks),
                number(row, "ours_isaac_actions_planned_std")),
            "Pick attempts": mean_std(n, 0.0),
            "Knocks": mean_std(knocks, 0.0),
            "Pushes": mean_std(0.0, 0.0),
            "Execution time (s)": mean_std(number(row, "ours_isaac_execution_time_sec_mean"),
                                             number(row, "ours_isaac_execution_time_sec_std")),
            "Success (\%)": percent(number(row, "ours_isaac_success_rate")),
            "Objects completed (\%)": percent_already_scaled(
                number(row, "ours_isaac_object_completion_percentage_mean"),
                number(row, "ours_isaac_object_completion_percentage_std")),
            "Failed actions": fixed(number(row, "ours_isaac_failed_picks_mean") +
                                      number(row, "ours_isaac_failed_pushes_mean"), 2),
        })
        pick_mean = number(row, "random_push_isaac_pick_attempts_mean")
        push_mean = number(row, "random_push_isaac_push_attempts_mean",
                           number(row, "random_push_isaac_push_actions_mean"))
        result.append({
            **common,
            "Method": "Online random Push",
            "Plan/replan time (s)": mean_std(
                number(row, "random_push_isaac_live_replan_time_sec_mean"),
                number(row, "random_push_isaac_live_replan_time_sec_std"), 4),
            "Action attempts": fixed(pick_mean + push_mean, 2),
            "Pick attempts": mean_std(pick_mean,
                                       number(row, "random_push_isaac_pick_attempts_std")),
            "Knocks": mean_std(0.0, 0.0),
            "Pushes": mean_std(push_mean,
                                number(row, "random_push_isaac_push_attempts_std",
                                       number(row, "random_push_isaac_push_actions_std"))),
            "Execution time (s)": mean_std(
                number(row, "random_push_isaac_execution_time_sec_mean"),
                number(row, "random_push_isaac_execution_time_sec_std")),
            "Success (\%)": percent(number(row, "random_push_isaac_success_rate")),
            "Objects completed (\%)": percent_already_scaled(
                number(row, "random_push_isaac_object_completion_percentage_mean"),
                number(row, "random_push_isaac_object_completion_percentage_std")),
            "Failed actions": fixed(
                number(row, "random_push_isaac_failed_picks_mean") +
                number(row, "random_push_isaac_failed_pushes_mean"), 2),
        })
    return result


def generate_paper_tables(batch: Path, print_tables: bool = True) -> list[Path]:
    specs = [
        ("Table 4 -- Proposed method: critical paper metrics",
         proposed_paper_rows(read_csv(batch / "table_1_our_method_full.csv")),
         batch / "table_4_our_method_paper"),
        ("Table 5 -- Planning comparison: optimal versus random feasible Knock",
         random_knock_paper_rows(read_csv(batch / "table_2_planning_vs_random_knock.csv")),
         batch / "table_5_planning_vs_random_knock_paper"),
        ("Table 6 -- Physical comparison: optimal Knock--Pick versus random Push",
         random_push_paper_rows(read_csv(batch / "table_3_ours_vs_random_push.csv")),
         batch / "table_6_ours_vs_random_push_paper"),
    ]
    for title, rows, base in specs:
        _write_table(title, rows, base, print_tables)
    bases = [base for _, _, base in specs]
    manifest_path = batch / "manifest.json"
    if manifest_path.is_file():
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
        full = manifest.get("full_tables", manifest.get("tables", []))
        manifest["full_tables"] = full[:3]
        manifest["paper_tables"] = [str(base) for base in bases]
        manifest["tables"] = manifest["full_tables"] + manifest["paper_tables"]
        manifest_path.write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    return bases


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("batch", type=Path,
                        help="Batch directory containing tables 1--3")
    parser.add_argument("--quiet", action="store_true")
    args = parser.parse_args()
    generate_paper_tables(args.batch.resolve(), not args.quiet)


if __name__ == "__main__":
    main()
